// Renders src/content/index.generated.ts: the metadata the app needs before any module pack
// has loaded (topic outlines, MCQ tags, walkthrough slugs). Regenerate with `npm run build:index`;
// tests/content-index.test.ts fails when the committed file is stale.
import type { McqMeta, TopicMeta } from '../../src/content/schema';
import { PACKS } from '../../src/content/all';

export function renderContentIndex(): string {
  const topics: TopicMeta[] = PACKS.flatMap((p) => p.topics).map((t) => {
    const { sections, interviewQuestions, revision, resources, recognition: _r, ...rest } = t;
    void _r; void resources;
    return { ...rest, sectionIds: sections.map((s) => s.id), counts: { interviewQuestions: interviewQuestions.length, flashcards: revision.flashcards.length } };
  });
  const mcqs: McqMeta[] = PACKS.flatMap((p) => p.mcqs).map((q) => ({
    id: q.id, topicIds: q.topicIds, moduleId: q.moduleId, type: q.type, difficulty: q.difficulty, verified: q.verified,
    title: q.stemMd.replace(/[`*_]/g, '').replace(/\s+/g, ' ').trim().slice(0, 90),
  }));
  const slugs = PACKS.flatMap((p) => Object.keys(p.walkthroughs ?? {})).sort();
  // TypeScript gives up ("union type too complex") on array literals with ~1000 object literals,
  // so each list is emitted as chunks of at most 250 entries that are spread into the export.
  const CHUNK = 250;
  const emit = (name: string, type: string, xs: unknown[]): string => {
    const parts: string[] = [];
    for (let i = 0; i < xs.length; i += CHUNK) {
      const body = xs.slice(i, i + CHUNK).map((x) => '  ' + JSON.stringify(x) + ',').join('\n');
      parts.push('const ' + name + '_' + i / CHUNK + ': ' + type + '[] = [\n' + body + '\n];\n');
    }
    const spread = parts.map((_, i) => '...' + name + '_' + i).join(', ');
    return parts.join('\n') + '\nexport const ' + name + ': ' + type + '[] = [' + spread + '];\n';
  };
  return `// GENERATED by scripts/build-content-index.ts from the module packs. Do not edit by hand.
import type { McqMeta, TopicMeta } from './schema';

${emit('TOPIC_META', 'TopicMeta', topics)}
${emit('MCQ_META', 'McqMeta', mcqs)}
export const WALKTHROUGH_SLUGS: string[] = ${JSON.stringify(slugs)};
`;
}
